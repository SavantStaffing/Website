-- =========================================================================
-- Job Scout: who gets ingested.
--
--   As You Sow gate only for companies with 1,000+ employees
--     (scout_settings.as_you_sow_min_employees). Its DEI score mostly measures
--     published workforce-diversity reporting, which smaller companies rarely
--     produce; holding them to it blocked well-regarded mid-size employers.
--     Headcounts come from the As You Sow list itself (num_emp).
--   At most 5 postings per position type per employer
--     (scout_settings.max_per_position; src/lib/scout/position.ts).
--   Postings older than 21 days aren't ingested (scout_settings.max_age_days).
-- =========================================================================

ALTER TABLE public.company_ratings
  ADD COLUMN employees INTEGER CHECK (employees >= 0);

ALTER TABLE public.scout_settings
  ADD COLUMN as_you_sow_min_employees INTEGER NOT NULL DEFAULT 1000
    CHECK (as_you_sow_min_employees >= 0),
  ADD COLUMN max_per_position INTEGER NOT NULL DEFAULT 5 CHECK (max_per_position > 0),
  ADD COLUMN max_age_days INTEGER NOT NULL DEFAULT 21 CHECK (max_age_days > 0);

